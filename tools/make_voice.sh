#!/bin/bash
# Generates the co-driver's voice clips into sounds/ (macOS only).
# Needs the built-in `say` command and ffmpeg.
#
#   tools/make_voice.sh            # British voice "Daniel"
#   tools/make_voice.sh Samantha   # any other installed voice
#
# The game only needs the resulting .wav files and sounds/index.lua,
# so this script never has to run on the gaming PC.

set -euo pipefail
cd "$(dirname "$0")/.."

VOICE="${1:-Daniel}"
RATE=185
OUT="sounds"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

# Trim silence at both ends, short fade-out, 44.1 kHz mono 16-bit PCM.
TRIM="silenceremove=start_periods=1:start_threshold=-50dB,areverse,silenceremove=start_periods=1:start_threshold=-50dB,areverse"

clip() {  # clip <file name> <text to speak>
  say -v "$VOICE" -r "$RATE" -o "$TMP/$1.aiff" "$2"
  ffmpeg -loglevel error -y -i "$TMP/$1.aiff" -af "$TRIM,apad=pad_dur=0.04" \
    -ar 44100 -ac 1 -c:a pcm_s16le "$OUT/$1.wav"
}

for dir in left right; do
  clip "hairpin_$dir" "Hairpin $dir"
  clip "tight_$dir"   "Tight $dir"
  clip "medium_$dir"  "Medium $dir"
  clip "fast_$dir"    "Fast $dir"
  clip "kink_$dir"    "Kink $dir"
  clip "then_$dir"    "then $dir"
done
clip "brake"    "Brake!"
clip "best_lap" "Best lap"
clip "throttle" "Throttle"
clip "teacher_ready" "Teacher lap recorded"

# Live coaching, spoken while you drive the corner.
clip "brake_harder"  "Brake harder!"
clip "ease_off"      "Ease off the brake"
clip "too_early"     "Too early"
clip "turn_in"       "Turn in"
clip "wait"          "Wait"
clip "full_throttle" "Full throttle"
clip "stay_flat"     "Stay on the throttle"
clip "move_left"     "Move left"
clip "move_right"    "Move right"

# The lesson plan: a reminder before the focus corner, and the verdict after it.
clip "tip_brake_later"      "Brake a little later here"
clip "tip_brake_earlier"    "Brake a little earlier here"
clip "tip_lift"             "No brake, just lift"
clip "tip_more_speed"       "Carry more speed"
clip "tip_patience"         "Be patient with the throttle"
clip "tip_throttle_earlier" "Earlier on the throttle"
clip "tip_no_coast"         "No coasting"
clip "tip_apex"             "Get close to the apex"
clip "tip_exit"             "Full throttle on the exit"
clip "tip_trail"            "Trail the brake into the corner"
clip "tip_push"             "Find the limit here"
clip "tip_steady"           "Same brake point every lap"
clip "tip_smooth"           "Smooth hands"
clip "tip_less_lock"        "Less steering"
clip "level_up"             "Level up"
clip "car_left"   "Car left"
clip "car_right"  "Car right"
clip "three_wide" "Three wide"
clip "clear"      "Clear"
clip "streak_3"   "Three in a row"
clip "streak_5"   "Five in a row"
clip "streak_10"  "Ten in a row"
clip "streak_20"  "Twenty in a row. That is a stint."
clip "licence_up" "New licence"
clip "good"     "Good"
clip "nice"     "Nice"
clip "better"   "Better"
clip "thats_it" "That's it"
clip "fixed"    "Sorted. Well done."

# A short two-tone beep for people who prefer it to the word "brake".
ffmpeg -loglevel error -y -f lavfi -i "sine=frequency=1320:duration=0.16" \
  -af "afade=t=in:d=0.01,afade=t=out:st=0.12:d=0.04,volume=0.7" \
  -ar 44100 -ac 1 -c:a pcm_s16le "$OUT/beep.wav"

# Clip lengths, so the app knows when one phrase ends and the next may start.
{
  echo "-- Generated by tools/make_voice.sh (voice: $VOICE). Clip lengths in seconds."
  echo "return {"
  for f in "$OUT"/*.wav; do
    name="$(basename "$f" .wav)"
    dur="$(ffprobe -v error -show_entries format=duration -of csv=p=0 "$f")"
    printf "  %s = %.2f,\n" "$name" "$dur"
  done
  echo "}"
} > "$OUT/index.lua"

echo "Wrote $(ls "$OUT"/*.wav | wc -l | tr -d ' ') clips to $OUT/ with voice $VOICE"
